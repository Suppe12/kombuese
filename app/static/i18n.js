// Amounts with units inside a text: "2 EL Öl" → "2 tbsp Öl", a unit alone ("Stück", "da") as well
const AMOUNT = '[\\d¼½¾⅓⅔⅛]+(?:[.,]\\d+)?(?:\\s*[–-]\\s*\\d+(?:[.,]\\d+)?)?';
const UNITS_RE = Object.keys(TEXTS[LANG]._units).length ? new RegExp(`(${AMOUNT})\\s+(${Object.keys(TEXTS[LANG]._units).filter(k => k !== 'da')
  .map(k => k.replace('.', '\\.')).join('|')})(?=$|[\\s,;)·])`, 'g') : null;
function units(s) {
  if (!s || !UNITS_RE) return s;
  const one = TEXTS[LANG]._units[String(s).trim()];
  return one !== undefined ? one : String(s).replace(UNITS_RE, (m, n, u) => `${n} ${unit(u)}`);
}
// Server messages: exact German texts first, then the texts with placeholders in the order of the dictionary
const SRV = (() => {
  const exact = {}, patterns = [];
  for (const [k, v] of Object.entries(TEXTS.de)) {
    if (!k.startsWith('srv.')) continue;
    if (!/\{\w+\}/.test(v)) { exact[v] = k; continue; }
    const names = [], src = v.split(/(\{\w+\})/).map(x => { const m = /^\{(\w+)\}$/.exec(x); if (m) { names.push(m[1]); return '(.+?)'; } return x.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }).join('');
    patterns.push([new RegExp('^' + src + '$'), k, names]);
  }
  return { exact, patterns };
})();
function srv(s) {
  if (LANG === 'de' || typeof s !== 'string' || !s.trim()) return s;
  const k = SRV.exact[s.trim()]; if (k) return t(k);
  for (const [re, key, names] of SRV.patterns) { const m = re.exec(s.trim()); if (m) return t(key, Object.fromEntries(names.map((n, i) => [n, units(m[i + 1])]))); }
  return s;
}
