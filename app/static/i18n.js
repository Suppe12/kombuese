// Language of Kombüse: German or English per device, new devices start in the household language.
// All UI texts live here, one dictionary per language (TEXTS.de, TEXTS.en) with the same keys. The pages call
//   t('section.key', { name: … })   placeholders {name}; plural forms as { one, other }, chosen by the number in {n}
// and mark static HTML with data-t="key" (first text of the element), data-t-title and data-t-placeholder (i18nStatic()).
// Units, supermarket categories, meal types and recipe categories keep their German keys from the API and are only
// mapped for display (unit(), units(), cat(), rcat(), mealType()). User content (recipe names, ingredients, steps, notes,
// card titles) never goes through t(). The server writes its messages in German: srv() shows the known ones (section srv)
// in the device language. New text: add the key to both dictionaries; a missing key falls back to English and warns in the console.
const LANG = (() => {
  try {
    let l = localStorage.getItem('ft-lang');
    if (!l) {  // new devices start in the household language (prepended by the server), otherwise as before
      l = window.KOMBUESE_LANG || (Object.keys(localStorage).some(k => k.startsWith('ft-') || k.startsWith('mp:')) ? 'de' : 'en');
      localStorage.setItem('ft-lang', l);
    }
    return l === 'de' ? 'de' : 'en';
  } catch (e) { return 'en'; }
})();
document.documentElement.lang = LANG;
function setLang(l) { try { localStorage.setItem('ft-lang', l); } catch (e) {} location.reload(); }

