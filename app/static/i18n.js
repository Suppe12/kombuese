// ======== Functions ========
const PLURAL = new Intl.PluralRules(LANG);
function t(key, p) {
  let s = TEXTS[LANG][key];
  if (s === undefined) s = TEXTS.en[key];
  if (s === undefined) { console.warn('i18n: missing key ' + key); return key; }
  if (Array.isArray(s)) return s;
  if (typeof s === 'object') s = s[PLURAL.select(Number(String(p && p.n).replace(',', '.')))] ?? s.other;
  return p ? s.replace(/\{(\w+)\}/g, (m, k) => p[k] ?? m) : s;
}
// Static texts of a page: data-t replaces the first text of the element (child elements such as badges stay)
function i18nStatic(root = document) {
  root.querySelectorAll('[data-t]').forEach(el => {
    const n = [...el.childNodes].find(x => x.nodeType === 3 && x.nodeValue.trim());
    if (n) n.nodeValue = t(el.dataset.t); else el.prepend(t(el.dataset.t));
  });
  for (const a of ['title', 'placeholder']) root.querySelectorAll(`[data-t-${a}]`).forEach(el => el.setAttribute(a, t(el.getAttribute('data-t-' + a))));
}
